"""Example module for the uptimer Python SDK."""


def hello_world() -> str:
    """
    Return a hello world message.

    Returns:
        A greeting message.
    """
    return "Hello, World!"


def add_numbers(a: int, b: int) -> int:
    """
    Add two numbers together.

    Args:
        a: First number
        b: Second number

    Returns:
        The sum of a and b
    """
    return a + b
